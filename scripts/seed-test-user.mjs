import { register } from 'node:module'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import 'dotenv/config'

register('./ts-resolver.mjs', import.meta.url)

const { prisma } = await import('../lib/db.ts')
const { hashPassword } = await import('../lib/password.ts')
const { Role } = await import('../generated/prisma/enums.ts')

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT_FILE = path.join(PROJECT_ROOT, 'testusers.md')

const args = new Set(process.argv.slice(2))
const markVerified = args.has('--verified')

const TEST_USER = {
  email: 'owner.test@operafrika.local',
  password: 'Operafrika!2026',
  name: 'Test Owner',
  businessName: 'Seed Test Business',
}

/**
 * Creates or updates a single Owner test user with a known password, then
 * writes the credentials to testusers.md.
 */
async function main() {
  const passwordHash = await hashPassword(TEST_USER.password)

  const existing = await prisma.user.findUnique({
    where: { email: TEST_USER.email },
  })

  let user = existing

  if (existing) {
    user = await prisma.user.update({
      where: { id: existing.id },
      data: { passwordHash },
    })
    console.log('Updated existing test user:', user.email)
  } else {
    const business = await prisma.business.create({
      data: {
        name: TEST_USER.businessName,
        businessType: 'General',
        currency: 'NGN',
      },
    })

    const branch = await prisma.branch.create({
      data: { businessId: business.id, name: 'Main Branch' },
    })

    user = await prisma.user.create({
      data: {
        email: TEST_USER.email,
        passwordHash,
        role: Role.OWNER,
        businessId: business.id,
        branchAccess: { create: { branchId: branch.id } },
        emailVerifiedAt: markVerified ? new Date() : null,
      },
    })

    await prisma.subscription.create({
      data: {
        businessId: business.id,
        planName: 'Free (Test Period)',
        price: 0,
        renewalDate: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000),
      },
    })

    console.log('Created test user:', user.email)
  }

  if (markVerified) {
    user = await prisma.user.update({
      where: { id: user.id },
      data: { emailVerifiedAt: new Date() },
    })
  }

  const contents = `# Test users

Generated by \`npm run seed:test-user\`. Local development accounts only.
Never use these credentials against a shared or production database.

| Email | Password | Role | Business | Email verified | User id |
| --- | --- | --- | --- | --- | --- |
| ${user.email} | ${TEST_USER.password} | ${user.role} | ${TEST_USER.businessName} | ${user.emailVerifiedAt ? 'yes' : 'no'} | ${user.id} |

## Notes

- \`npm run seed:test-user\` is idempotent. Run it again to reset the password
  of the same account rather than creating a duplicate.
- \`npm run seed:test-user -- --verified\` sets \`emailVerifiedAt\`, so the
  account goes straight to \`/app\` after login. Without the flag the account
  is unverified and the login flow redirects to \`/app/auth/verify-email\`.
- To test a ban, set \`bannedAt\` on the user row. To test a temporary lock,
  set \`lockedUntil\` to a future date. Both block the session at the proxy.
`

  await writeFile(OUTPUT_FILE, contents, 'utf8')
  console.log('Wrote', path.relative(PROJECT_ROOT, OUTPUT_FILE))
  console.log('Email:    ', user.email)
  console.log('Password: ', TEST_USER.password)
}

main()
  .then(async () => {
    await prisma.$disconnect()
  })
  .catch(async (error) => {
    console.error(error)
    await prisma.$disconnect()
    process.exit(1)
  })
